#!/usr/bin/env python3
"""Generate lib/data/state-paths.ts from ~/workspace/seeds-hues/state-shapes/state-paths.json
(seeds-v2 brief #4).

Input (prepared by Hue; simplified Census-derived geometry, public domain):
{ <state-slug>: { name, viewBox, d } }  — `d` may also arrive as `paths: [...]`.

Output: STATE_SHAPES keyed by USPS state code, each { code, slug, name, viewBox, paths }.
The code comes from the fixed table below (the input has none); an input state missing from
the table, or a slug that doesn't match its name, fails loudly. Deterministic: entries sorted
by code. Usage: gen-state-paths.py [--write]   (dry-run by default)
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INPUT = ROOT.parent / "state-shapes" / "state-paths.json"
OUTPUT = ROOT / "lib" / "data" / "state-paths.ts"

CODES = {
    "Alabama": "AL", "Alaska": "AK", "Arizona": "AZ", "Arkansas": "AR", "California": "CA",
    "Colorado": "CO", "Connecticut": "CT", "Delaware": "DE", "Florida": "FL", "Georgia": "GA",
    "Hawaii": "HI", "Idaho": "ID", "Illinois": "IL", "Indiana": "IN", "Iowa": "IA",
    "Kansas": "KS", "Kentucky": "KY", "Louisiana": "LA", "Maine": "ME", "Maryland": "MD",
    "Massachusetts": "MA", "Michigan": "MI", "Minnesota": "MN", "Mississippi": "MS",
    "Missouri": "MO", "Montana": "MT", "Nebraska": "NE", "Nevada": "NV", "New Hampshire": "NH",
    "New Jersey": "NJ", "New Mexico": "NM", "New York": "NY", "North Carolina": "NC",
    "North Dakota": "ND", "Ohio": "OH", "Oklahoma": "OK", "Oregon": "OR", "Pennsylvania": "PA",
    "Rhode Island": "RI", "South Carolina": "SC", "South Dakota": "SD", "Tennessee": "TN",
    "Texas": "TX", "Utah": "UT", "Vermont": "VT", "Virginia": "VA", "Washington": "WA",
    "West Virginia": "WV", "Wisconsin": "WI", "Wyoming": "WY",
}
PATH_RE = re.compile(r"^[MLHVCSQTAZmlhvcsqtaz0-9.,\s-]+$")
VIEWBOX_RE = re.compile(r"^-?\d+(\.\d+)? -?\d+(\.\d+)? \d+(\.\d+)? \d+(\.\d+)?$")


def kebab(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def main() -> int:
    write = "--write" in sys.argv
    src = json.loads(INPUT.read_text())
    out = []
    for slug, v in src.items():
        name = v["name"]
        code = CODES.get(name)
        if not code:
            raise SystemExit(f"{slug}: no state code for {name!r}")
        if kebab(name) != slug:
            raise SystemExit(f"{slug}: slug does not match name {name!r} (expected {kebab(name)})")
        paths = v.get("paths") or ([v["d"]] if v.get("d") else [])
        if not paths or not all(PATH_RE.match(p) for p in paths):
            raise SystemExit(f"{slug}: missing or malformed path data")
        if not VIEWBOX_RE.match(v["viewBox"]):
            raise SystemExit(f"{slug}: malformed viewBox {v['viewBox']!r}")
        out.append({"code": code, "slug": slug, "name": name, "viewBox": v["viewBox"], "paths": paths})
    out.sort(key=lambda s: s["code"])

    lines = [
        "/**",
        " * US state outlines for the sellers' states (seeds-v2 brief #4). GENERATED by",
        " * scripts/gen-state-paths.py from ~/workspace/seeds-hues/state-shapes/state-paths.json —",
        " * do not edit by hand. Simplified Census-derived geometry (public domain).",
        " */",
        "",
        "export interface StateShapeData {",
        "  /** USPS code, = sellers.region */",
        "  code: string;",
        "  /** kebab-case state name: /state/{slug} */",
        "  slug: string;",
        "  name: string;",
        "  viewBox: string;",
        "  paths: readonly string[];",
        "}",
        "",
        "export const STATE_SHAPES: Readonly<Record<string, StateShapeData>> = {",
    ]
    for s in out:
        lines.append(f"  {s['code']}: {{")
        lines.append(f"    code: {json.dumps(s['code'])},")
        lines.append(f"    slug: {json.dumps(s['slug'])},")
        lines.append(f"    name: {json.dumps(s['name'])},")
        lines.append(f"    viewBox: {json.dumps(s['viewBox'])},")
        lines.append("    paths: [")
        for p in s["paths"]:
            lines.append(f"      {json.dumps(p)},")
        lines.append("    ],")
        lines.append("  },")
    lines.append("};")
    text = "\n".join(lines) + "\n"

    print(f"states: {len(out)} — {' '.join(s['code'] for s in out)}")
    if write:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(text)
        print("WROTE", OUTPUT)
    else:
        print("dry-run — pass --write to save")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
